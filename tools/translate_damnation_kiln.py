def apply_translations(path, trans_map):
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    for entry in data:
        eid = entry["id"]
        if eid in trans_map:
            new_text = trans_map[eid]
            assert len(new_text) == len(entry["text"]), (
                f"line count mismatch for {eid}: {len(new_text)} vs {len(entry['text'])}"
            )
            entry["text"] = new_text
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    return data


